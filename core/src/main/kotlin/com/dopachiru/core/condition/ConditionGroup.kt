package com.dopachiru.core.condition

/**
 * 条件の仲間分け。
 *
 * ## なぜ要るのか
 *
 * 条件が20種類まで増えて、**選ぶ画面が平らな一覧になっていた**。
 * 名前だけ20個並べられても、何を選べばいいのかは文字から読み取れない
 * ── 「本当にやりたいことはできるはずなのに、やり方が複雑に見える」の
 * 大半がここだった。
 *
 * 仲間で括ると、まず「どういう縛りか」を4つから選び、そのあと数個から選ぶ形になる。
 * 選択肢の総数は変わらないが、**一度に見る数**が減る。
 *
 * ## 順番に意味がある
 *
 * [USAGE] を先頭に置いてある。「n分使ったらm分休む」がこの道具のいちばんの芯で、
 * そこに辿り着くまでに他を19個見せる理由が無い。
 */
enum class ConditionGroup(
    val label: String,
    /** 選ぶ画面の見出しの下に出す一言。 */
    val summary: String,
) {
    /** 使いすぎを止める。この道具の芯。 */
    USAGE("使いすぎで止める", "何分使ったか・何回開いたかで決める"),

    /** 時間と曜日と予定。 */
    TIME("時間で区切る", "時間帯・曜日・先に取った予約や予定で決める"),

    /** 開く癖・アプリの中の画面。 */
    TRIGGER("開く癖を狙う", "開き直し・アプリの連鎖・ショートの画面など、引き金そのもの"),

    /** 効き目の調整。慣れ対策や、たまにだけ出すもの。 */
    TUNING("効き目を調整する", "たまにだけ出す・慣れたら強める。単体では使わない"),

    /** 条件なし。 */
    ALWAYS("条件なし", "いつでも。まず全部止めたいとき"),
    ;

    companion object {
        /** 選ぶ画面に並べる順。[TUNING] を後ろにするのは、単体では使わないため。 */
        val ORDER: List<ConditionGroup> = listOf(USAGE, TIME, TRIGGER, ALWAYS, TUNING)
    }
}
