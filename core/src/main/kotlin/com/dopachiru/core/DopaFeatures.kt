package com.dopachiru.core

/**
 * 一時的に止めている機能の switch。
 *
 * 消さずに止めてあるのは、また使う見込みがあるものだけ。見込みが無くなったら
 * 素直に消す ── 「いつか使うかもしれない」で残したコードは腐る。
 */
object DopaFeatures {

    /**
     * カレンダーの読み取り。**いまは凍結中**(2026-08-15〜)。
     *
     * 連携相手のスキマスが完全ローカルになり、学習予定はブロードキャストで
     * 直接届くようになった([com.dopachiru.core.condition.types.StudySessionCondition])。
     * カレンダーを経由する必要が無くなったので、読みに行くのをやめている。
     *
     * ## 凍結中に何が起きるか
     *  - 端末のカレンダーを一切読まない(Android の READ_CALENDAR も宣言から外してある)
     *  - `calendar_busy` 条件は**常に成立しない**
     *  - `Gate.CalendarWindow` は**常に通過扱い**
     *  - 条件・ゲート・雛形の選択肢に出ない
     *
     * 条件とゲートで倒す向きが逆なのは、どちらも「凍結で縛りがきつくなる」ほうを
     * 避けているため。素直にカレンダーを空として扱うと、
     * 「予定が無いあいだ封印」は永久に成立し、
     * 「予定が入っているあいだだけ変更できる」は永久に閉じてルールを直せなくなる。
     * 止めた機能が、止めたせいで人を縛るのはおかしい。
     *
     * ## 戻すとき
     *  1. ここを `true` にする
     *  2. `app/src/main/AndroidManifest.xml` に `READ_CALENDAR` を戻す
     *
     * 保存済みのルールとゲートはそのまま残っているので、戻せば元どおり動く。
     */
    const val CALENDAR_ENABLED = false
}
